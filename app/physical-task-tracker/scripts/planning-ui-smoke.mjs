/** Mobile UI verification through intercepted real handlers; no listening server. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, mkdir, readFile, rm } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createServer } from '../dist/serve-dashboard.js';
import { addGoal } from '../dist/lib/goals.js';
import { createTask, configurePlanning, proposePlan, decidePlan, planningView, saveCommitment } from '../dist/lib/task-planning.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const out = resolve(process.argv[2] || './planning-ui-qa'); await mkdir(out, { recursive: true });
const root = await mkdtemp(join(tmpdir(), 'planning-ui-'));
let browser;
try {
  const goal = await addGoal(root, { text: 'Prepare 50 trays', success_criteria: '50 trays pass inspection', deadline: '2030-01-10' });
  const other = await addGoal(root, { text: 'Prepare delivery' });
  const task = createTask(root, { text: 'Stage materials', completion_criteria: 'Supplies ready', active_minutes: 30, estimate_source: 'Synthetic operator estimate', links: [{ goal_id: goal.id, origin: 'human', review: 'confirmed', explanation: 'Materials required before filling' }] }, 'ui');
  configurePlanning(root, 1, { timezone: 'America/New_York', person: 'operator', max_minutes: 180, resources: {}, availability: [{ start: '2030-01-10T09:00:00-05:00', end: '2030-01-10T12:00:00-05:00' }] });
  saveCommitment(root, { id: 'lunch', title: 'Lunch remains visible', start: '2030-01-10T11:00:00-05:00', end: '2030-01-10T11:30:00-05:00', blocking: true, resources: [] });
  const p = proposePlan(root, '2030-01-10', '2030-01-10T08:00:00-05:00'); decidePlan(root, p.id, 'accepted', 'Synthetic acceptance', '2030-01-10T08:00:00-05:00');
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const handler = createServer(root).listeners('request')[0];
  const html = await readFile(new URL('../dist/dashboard/index.html', import.meta.url), 'utf8');
  await page.route('**/*', async route => {
    const request = route.request(), url = new URL(request.url());
    if (url.pathname === '/') return route.fulfill({ status: 200, contentType: 'text/html', body: html });
    let status = 500, headers = {}, body = Buffer.alloc(0);
    await handler({ method: request.method(), url: url.pathname + url.search, async *[Symbol.asyncIterator]() { const data = request.postDataBuffer(); if (data) yield data; } }, { writeHead(code, values) { status = code; headers = values; }, end(value = '') { body = Buffer.from(value); } });
    await route.fulfill({ status, headers, body });
  });
  await page.goto('http://localhost/');
  await page.getByRole('tab', { name: 'Plan', exact: true }).click();
  await page.locator('#planningtasks button[data-opentask]').first().click();
  await page.locator('#taskeditform').waitFor();
  const relationship = page.locator(`[data-linkgoal="${other.id}"]`);
  await relationship.locator('select').selectOption('confirmed'); await relationship.locator('input').fill('Supplies also support delivery');
  await page.locator('#taskeditform [name=reason]').fill('Synthetic second-goal assignment');
  await page.locator('#taskeditform button[type=submit]').click();
  await page.getByText('Saved. Review the updated task and day plan.', { exact: true }).waitFor();
  assert.equal(planningView(root).tasks[0].links.length, 2);
  await page.reload(); await page.getByRole('tab', { name: 'Plan', exact: true }).click();
  await page.locator('#planningtasks [data-goaldetail]').first().waitFor();
  assert.equal(await page.locator('#planningtasks [data-goaldetail]').count(), 2);
  await page.screenshot({ path: join(out, 'planning-mobile.png'), fullPage: true });
  await page.locator('#planningtasks [data-taskcalendar]').click();
  await page.locator('#cal .ev.task').waitFor();
  await page.locator('#calgoalfilter').selectOption(other.id);
  await page.getByText('Lunch remains visible', { exact: false }).waitFor();
  await page.locator('#cal .ev.task').click();
  await page.getByRole('button', { name: 'Open task and record work' }).click();
  await page.locator('#taskeditform [name=execution]').selectOption('done');
  await page.locator('#taskeditform [name=reason]').fill('Synthetic completion');
  await page.locator('#taskeditform button[type=submit]').click();
  await page.getByText('Saved. Review the updated task and day plan.', { exact: true }).waitFor();
  assert.equal(planningView(root).tasks.find(t => t.id === task.id).execution, 'done');
  assert.ok(planningView(root).goals.every(g => g.status === 'open'));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: ['goal assignment', 'reload persistence', 'calendar goal filter retains commitments', 'task/calendar navigation', 'task completion preserves goal outcome', 'mobile bounds'], screenshots: out }));
} finally { await browser?.close(); await rm(root, { recursive: true, force: true }); }
